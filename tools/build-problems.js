// Writes site/problems.html: every Troubleshoot entry as plain HTML that
// reads without JavaScript and that search engines can index, since the
// app's own #fix/<id> links are fragments of a single page.
// Run with: node tools/build-problems.js   (--check fails if the file is stale)
"use strict";
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const out = path.join(root, "site/problems.html");

function load() {
  global.window = global.window || {};
  require(path.join(root, "site/data.js"));
  require(path.join(root, "site/playground.js"));
  return { Q: window.TRACK, scenarios: window.KQSim.SCENARIOS };
}

const esc = (text) => String(text).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
// Text with `code` spans, as the app renders it.
const rich = (text) => text.split(/(`[^`]+`)/).map((part) =>
  part.startsWith("`") ? `<code>${esc(part.slice(1, -1))}</code>` : esc(part)).join("");
const list = (tag, items, fmt) => `<${tag}>\n${items.map((t) => `          <li>${fmt(t)}</li>`).join("\n")}\n        </${tag}>`;

function render() {
  const { Q, scenarios } = load();
  const titles = Object.fromEntries(scenarios.map((s) => [s.id, s.title]));
  const byStatus = Object.fromEntries(Q.doctor.map((d) => [d.status, d]));
  const description = `How to fix ${Q.doctor.length} common Kubernetes errors, from CrashLoopBackOff, ImagePullBackOff and Pending Pods to Forbidden and x509 certificate errors: the exact error text, the cause, the commands that confirm it, the fix and how to prevent it.`;

  const problem = (d) => {
    const lv = Q.levels.find((l) => l.id === d.level);
    return `
      <article class="card problem" id="${d.id}" aria-labelledby="${d.id}-title">
        <h3 id="${d.id}-title">${esc(d.status)}</h3>
        <h4>Symptom</h4>
        <p>${rich(d.symptom)}</p>
        <h4>Error or output</h4>
        <pre class="fix-error"><code>${esc(d.error)}</code></pre>
        <h4>Why it happens</h4>
        <p>${esc(d.meaning)}</p>
        ${list("ul", d.causes, esc)}
        <h4>Confirm with</h4>
        <pre><code>${esc(d.commands.join("\n"))}</code></pre>
        <h4>Fix</h4>
        ${list("ol", d.fix, rich)}
        <h4>Prevent it</h4>
        ${list("ul", d.prevent, rich)}
        <p class="note"><strong>Now learn it:</strong> break and fix it yourself in ${d.scenarios.map((id) => `<a href="./#play/${id}">${esc(titles[id])}</a>`).join(" · ")}, then take <a href="${Q.repo}/tree/main/labs/${lv.slug}">Level ${lv.id} · ${esc(lv.title)}</a> on a real cluster. <a href="./#fix/${d.id}">Open this in the interactive reference</a>.</p>
      </article>`;
  };

  return `<!doctype html>
<html lang="en" data-mode="fix">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta http-equiv="Content-Security-Policy" content="default-src 'self'; script-src 'self'; style-src 'self'; img-src 'self' data:; connect-src 'none'; base-uri 'none'; form-action 'none'">
  <meta name="description" content="${esc(description)}">
  <meta property="og:type" content="article">
  <meta property="og:site_name" content="DevOps Nimbus">
  <meta property="og:title" content="Kubernetes errors and how to fix them">
  <meta property="og:description" content="${esc(description)}">
  <meta property="og:url" content="${Q.site}problems.html">
  <link rel="canonical" href="${Q.site}problems.html">
  <title>Kubernetes errors and how to fix them · Kubernetes · DevOps Nimbus</title>
  <link rel="stylesheet" href="style.css">
  <link rel="icon" href="favicon.svg" type="image/svg+xml">
</head>
<body>
  <!-- Generated by tools/build-problems.js from site/data.js. Do not edit by hand. -->
  <a class="skip" href="#main">Skip to content</a>
  <header class="top">
    <div class="wrap top-inner">
      <a class="brand" href="./" aria-label="DevOps Nimbus Kubernetes, home">
        <img class="mark" src="nimbus.svg" alt="" width="37" height="22">
        DevOps Nimbus <span class="brand-track">Kubernetes</span>
      </a>
      <nav class="switch" aria-label="Mode">
        <a class="sw learn" href="./#path"><svg viewBox="0 0 16 16" width="15" height="15" aria-hidden="true"><path d="M2.5 3.2c1.8-.6 3.6-.4 5.5.8 1.9-1.2 3.7-1.4 5.5-.8v9c-1.8-.6-3.6-.4-5.5.8-1.9-1.2-3.7-1.4-5.5-.8zM8 4v9" fill="none" stroke="currentColor" stroke-width="1.4" stroke-linejoin="round"/></svg>Learn</a>
        <a class="sw fix" href="./#doctor" aria-current="true"><svg viewBox="0 0 16 16" width="15" height="15" aria-hidden="true"><path d="M10.2 2.4a3.3 3.3 0 0 0-3.9 4.3L2.6 10.4a1.4 1.4 0 0 0 2 2l3.7-3.7a3.3 3.3 0 0 0 4.3-3.9l-2 2-1.7-.4-.4-1.7z" fill="none" stroke="currentColor" stroke-width="1.4" stroke-linejoin="round"/></svg>Fix</a>
      </nav>
    </div>
    <div class="wrap sub-row">
      <nav class="subnav" aria-label="Sections">
        <div class="mode learn" role="group" aria-label="Learn">
          <span class="mode-k">Step by step, basics to production</span>
          <a href="./#path">Path</a>
          <a href="./#quiz">Quiz</a>
          <a href="./#xray">YAML X-ray</a>
          <a href="./#arch">K8s arch</a>
        </div>
        <div class="mode fix" role="group" aria-label="Fix">
          <span class="mode-k">Something broken? Find the cause and the fix</span>
          <a href="./#doctor" aria-current="page">Troubleshoot</a>
          <a href="./#cheats">Cheat sheet</a>
        </div>
      </nav>
    </div>
  </header>

  <main id="main" class="wrap problems">
    <h1>Kubernetes errors and how to fix them</h1>
    <p class="lede">${Q.doctor.length} problems you will meet in real clusters. Each one gives the exact error, why it happens, the commands that confirm it, the fix and how to prevent it, then a scenario to break and fix it yourself. Replace names in angle brackets with your own. To search by pasting an error, use the <a href="./#doctor">interactive reference</a>.</p>
    <nav class="problems-toc" aria-label="Problems">${Q.doctorGroups.map(([name, statuses]) => `
      <div>
        <h2>${esc(name)}</h2>
        ${list("ul", statuses, (s) => `<a href="#${byStatus[s].id}">${esc(s)}</a>`)}
      </div>`).join("")}
    </nav>
${Q.doctorGroups.map(([name, statuses]) => `
    <section aria-label="${esc(name)}">
      <h2>${esc(name)}</h2>${statuses.map((s) => problem(byStatus[s])).join("\n")}
    </section>`).join("\n")}
  </main>

  <footer class="foot">
    <div class="wrap foot-base">
      <p>© 2024–2026 Sandeep Komal Pothu and contributors.</p>
      <p>Open source under the <a href="${Q.repo}/blob/main/LICENSE">MIT License</a>. Built with no trackers, no cookies and nothing loaded from other sites.</p>
      <p class="foot-tm">Kubernetes® is a registered trademark of The Linux Foundation. This project is independent and not affiliated with the CNCF.</p>
    </div>
  </footer>
</body>
</html>
`;
}

if (require.main === module) {
  const html = render();
  if (process.argv.includes("--check")) {
    if (fs.readFileSync(out, "utf8") !== html) {
      console.error("site/problems.html is out of date: run node tools/build-problems.js");
      process.exit(1);
    }
  } else {
    fs.writeFileSync(out, html);
    console.log(`wrote ${path.relative(root, out)}`);
  }
}

module.exports = { render };
